## compare_wp3.R - agreement of the R port of WP3 with the archived Python results (wp3_mlss/gate_scores.csv, mlss_scenarios.csv, mlss_scenario_scores.csv, mlss_permutation_draws.csv)
args <- commandArgs(trailingOnly = FALSE); here <- dirname(normalizePath(sub("^--file=", "", args[grep("^--file=", args)][1])))
source(file.path(here, "agree.R"))
PY <- Sys.getenv("WP3_DIR", file.path(here, "..", "wp3_mlss")); RR <- Sys.getenv("R_OUT_DIR", file.path(here, "results_R", "wp3"))
res <- list()
res$gate <- agree_csv(file.path(PY, "gate_scores.csv"), file.path(RR, "gate_scores.csv"), tol = 1e-9)
res$scen <- agree_csv(file.path(PY, "mlss_scenarios.csv"), file.path(RR, "mlss_scenarios.csv"), tol = 2e-6)
res$scores <- agree_csv(file.path(PY, "mlss_scenario_scores.csv"), file.path(RR, "mlss_scenario_scores.csv"), tol = 2e-8)
res$draws <- agree_csv(file.path(PY, "mlss_permutation_draws.csv"), file.path(RR, "mlss_permutation_draws.csv"), tol = 2e-6)
cat(sprintf("\nWP3 agreement: %d of %d files agree\n", sum(vapply(res, function(r) r$ok, TRUE)), length(res)))
