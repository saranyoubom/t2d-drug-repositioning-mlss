## bench_numpy_rng.R - throughput of numpy_rng.R (prints draws per second)
args <- commandArgs(trailingOnly = FALSE)
here <- dirname(normalizePath(sub("^--file=", "", args[grep("^--file=", args)][1])))
source(file.path(here, "numpy_rng.R"))
tm <- function(label, n, expr) { t <- system.time(expr)[["elapsed"]]; cat(sprintf("%-34s %8.2f s   %10.0f per second\n", label, t, n / max(t, 1e-9))) }
g <- np_rng(2026)
tm("random(1e6)", 1e6, np_random(g, 1e6))
tm("random(1e6) again", 1e6, np_random(g, 1e6))
tm("standard_normal(1e6)", 1e6, np_standard_normal(g, 1e6))
tm("integers(0, 17, 1e6)", 1e6, np_integers(g, 0, 17, 1e6))
tm("1000 x permutation(12)", 1.2e4, for (i in 1:1000) np_permutation(g, 12))
tm("20 x permutation(1000)", 2e4, for (i in 1:20) np_permutation(g, 1000))
tm("2000 x choice(20, 6, no replace)", 1.2e4, for (i in 1:2000) np_choice_noreplace_idx(g, 20, 6))
tm("new generator + 10 draws, x200", 200, for (i in 1:200) { h <- np_rng(c(2026, i, 3, 1)); np_random(h, 10) })
