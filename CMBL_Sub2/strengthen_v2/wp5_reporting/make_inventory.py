"""make_inventory.py - list every Python script of the v2 work (strengthen_v2/ and its package folders) with the first sentence of its own module docstring and its 'Usage:' line, written to script_inventory.md.
Reads source files only (ast, no import, nothing is run).   Usage: python -I make_inventory.py"""
import os, sys, ast, re
sys.stdout.reconfigure(encoding='utf8')
HERE = os.path.dirname(os.path.abspath(__file__)); V2 = os.path.dirname(HERE)
FOLDERS = ['.', 'wp1_ins1_structure', 'wp2_benchmark2', 'wp3_mlss', 'wp4_islets', 'wp5_reporting']
rows = []
for f in FOLDERS:
    d = os.path.normpath(os.path.join(V2, f))
    for fn in sorted(os.listdir(d)):
        if not fn.endswith('.py'): continue
        p = os.path.join(d, fn)
        try: doc = ast.get_docstring(ast.parse(open(p, encoding='utf8').read())) or ''
        except SyntaxError: doc = '(could not be parsed)'
        text = re.sub(r'\s+', ' ', doc).strip(); first = re.split(r'(?<=[a-z0-9)])\.\s', text, maxsplit=1)[0][:260] if text else '(no docstring)'
        m = re.search(r'Usage:\s*(.+?)(?:\.\s|$)', re.sub(r'[ \t]+', ' ', doc.replace('\n', ' ')))
        rows.append(('strengthen_v2' if f == '.' else f, fn, first.replace('|', '/'), (m.group(1).strip()[:150] if m else '').replace('|', '/'), os.path.getsize(p)))
L = ['# Script inventory of the v2 work (generated by make_inventory.py from the module docstrings; nothing is run)', '', '| folder | script | purpose (first sentence of its docstring) | usage line | bytes |', '|---|---|---|---|---|']
for r in rows: L.append('| %s | `%s` | %s | %s | %d |' % r)
open(os.path.join(HERE, 'script_inventory.md'), 'w', encoding='utf8').write('\n'.join(L) + '\n'); print(len(rows), 'scripts listed')
