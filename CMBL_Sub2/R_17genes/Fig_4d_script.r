################################################################################
# FUNCTION TO GET SIGNIFICANT PAIRS
################################################################################

get_pairs <- function(data, method_name) {
  cat("  Analyzing:", method_name, "\n")
  
  data_clean <- na.omit(data)
  cor_results <- rcorr(as.matrix(data_clean), type = "pearson")
  cor_matrix <- cor_results$r
  p_matrix <- cor_results$P
  
  genes <- colnames(data_clean)
  n_genes <- length(genes)
  
  pairs <- character()
  for (i in 1:(n_genes-1)) {
    for (j in (i+1):n_genes) {
      if (!is.na(p_matrix[i, j]) && p_matrix[i, j] < 0.05) {
        pairs <- c(pairs, paste(genes[i], genes[j], sep = "_"))
      }
    }
  }
  
  cat("    Found", length(pairs), "significant pairs\n")
  return(pairs)
}

################################################################################
# EXTRACT SIGNIFICANT PAIRS FROM EACH METHOD
################################################################################

cat("\nExtracting significant correlation pairs...\n")

pairs_list <- list(
  "Hes1-\nnormalized" = get_pairs(hes1_norm, "Hes1-normalized"),
  "Kcnj11-\nNormalized" = get_pairs(kcnj11_norm, "Kcnj11-Normalized"),
  "Ins1-\nnormalized" = get_pairs(ins1_norm, "Ins1-normalized"),
  "Raw\nexpression" = get_pairs(raw_data, "Raw expression")
)

################################################################################
# IDENTIFY CONSENSUS PAIRS
################################################################################

cat("\nIdentifying consensus pairs...\n")

consensus_pairs <- Reduce(intersect, pairs_list)
