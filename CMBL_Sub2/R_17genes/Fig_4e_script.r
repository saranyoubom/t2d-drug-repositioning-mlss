rm(list = ls())
setwd("C:/Users/saran/OneDrive/VSCBIC/C2F-2025/Publication/Submission/CMBL_Sub2_291026/Analysis_outputs/R_17genes")

# Load required libraries
library(ggplot2)
library(reshape2)
library(ggcorrplot)
library(ggsci)

# Extract NPG color palette
npg_colors <- pal_npg("nrc")(10)

################################################################################
# LOAD HES1-NORMALIZED DATA FROM CSV
################################################################################

cat("\nLoading Hes1-normalized data from CSV file...\n")

# Load Hes1-normalized data generated by Fig_4c_script.R
hes1_norm <- read.csv("Fig_4c_Hes1_normalized_data.csv")

cat("Data loaded successfully!\n")
cat("Genes:", ncol(hes1_norm), "\n")
cat("Samples:", nrow(hes1_norm), "\n")

################################################################################
# CALCULATE CORRELATIONS
################################################################################

cat("\nCalculating correlation matrix...\n")

# Calculate correlation matrix
corr_e <- round(cor(hes1_norm, use = "pairwise.complete.obs"), 2)

# Compute p-values
p_mat_e <- cor_pmat(hes1_norm)

cat("Correlation matrix dimensions:", dim(corr_e), "\n")

################################################################################
# CREATE SIGNIFICANCE ANNOTATIONS
################################################################################

cat("\nCreating significance annotations...\n")

# Create asterisk labels ONLY for significant correlations
sig_labels <- matrix("", nrow = nrow(corr_e), ncol = ncol(corr_e))
sig_labels[p_mat_e < 0.05 & p_mat_e >= 0.01] <- "*"
sig_labels[p_mat_e < 0.01 & p_mat_e >= 0.001] <- "**"
sig_labels[p_mat_e < 0.001] <- "***"

# Count significant correlations
n_sig <- sum(p_mat_e < 0.05, na.rm = TRUE) / 2  # Divide by 2 for symmetric matrix
cat("Significant correlations:", n_sig, "\n")

################################################################################
# EXPORT DATA
################################################################################

cat("\nExporting data...\n")

# Export correlation matrix
corr_e_df <- as.data.frame(corr_e)
write.csv(corr_e_df, "Fig_4e_Hes1_normalized_correlations.csv", row.names = TRUE)

# Export p-value matrix
p_mat_e_df <- as.data.frame(p_mat_e)
write.csv(p_mat_e_df, "Fig_4e_Hes1_normalized_pvalues.csv", row.names = TRUE)

# Export significance annotations
sig_matrix_df <- as.data.frame(sig_labels)
rownames(sig_matrix_df) <- rownames(corr_e)
colnames(sig_matrix_df) <- colnames(corr_e)
write.csv(sig_matrix_df, "Fig_4e_significance_annotations.csv", row.names = TRUE)

################################################################################
# CREATE PLOT
################################################################################

cat("\nGenerating Panel (e): Hes1-Normalized Correlation Matrix...\n")

# Prepare data for ggplot
corr_long <- melt(corr_e)
p_long <- melt(p_mat_e)
sig_long <- melt(sig_labels)

plot_data <- data.frame(
  Gene1 = corr_long$Var1,
  Gene2 = corr_long$Var2,
  Correlation = corr_long$value,
  pvalue = p_long$value,
  Significance = sig_long$value
)

# Create the plot with NPG colors
panel_e <- ggplot(plot_data, aes(x = Gene1, y = Gene2)) +
  geom_tile(aes(fill = Correlation), color = "white", size = 0.5) +
  geom_text(aes(label = Significance), size = 2.5, fontface = "bold", 
            vjust = 0.7, family = "Arial") +
  scale_fill_gradient2(
    low = npg_colors[4],
    mid = "white",
    high = npg_colors[1],
    midpoint = 0,
    limits = c(-1, 1),
    name = "Pearson\nCorrelation"
  ) +
  coord_fixed() +
  theme_minimal() +
  theme(
    axis.text.x = element_text(angle = 90, hjust = 1, vjust = 0.5, size = 8, 
                               color = "black", face = "italic", family = "Arial"),
    axis.text.y = element_text(size = 8, color = "black", face = "italic", 
                               family = "Arial"),
    axis.title = element_blank(),
    legend.position = "top",
    legend.title = element_text(size = 8, family = "Arial"),
    legend.text = element_text(size = 7, family = "Arial"),
    legend.key.height = unit(0.3, "cm"),
    legend.key.width = unit(1, "cm"),
    panel.grid = element_blank(),
    plot.margin = margin(5, 5, 5, 5)
  )

################################################################################
# SAVE FIGURE
################################################################################

cat("\nSaving figure...\n")

ggsave("Fig_4e_Correlation_matrix_Hes1_normalized_annotated.png", plot = panel_e,
       width = 9.16, height = 9.16, units = "cm", dpi = 600)
ggsave("Fig_4e_Correlation_matrix_Hes1_normalized_annotated.svg", plot = panel_e,
       width = 9.16, height = 9.16, units = "cm", dpi = 600)

