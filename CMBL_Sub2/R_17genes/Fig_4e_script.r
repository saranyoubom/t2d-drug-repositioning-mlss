cat("Exported CSV files:\n")
cat(" - Fig_4e_Hes1_normalized_correlations.csv\n")
cat(" - Fig_4e_Hes1_normalized_pvalues.csv\n")
cat(" - Fig_4e_significance_annotations.csv\n\n")
cat("Generated figures:\n")
cat(" - Fig_4e_Correlation_matrix_Hes1_normalized_annotated.png\n")
cat(" - Fig_4e_Correlation_matrix_Hes1_normalized_annotated.svg\n\n")
cat("Statistics:\n")
cat(" Total gene pairs:", nrow(corr_e) * (nrow(corr_e) - 1) / 2, "\n")
cat(" Significant pairs:", n_sig, "\n")
cat(" Percentage:", round(100 * n_sig / (nrow(corr_e) * (nrow(corr_e) - 1) / 2), 1), "%\n")
cat("\n")

